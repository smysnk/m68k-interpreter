import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { format } from 'prettier';
import {
  M68000_ISA_MANIFEST,
  summarizeIsaCoverage,
  validateIsaManifest,
} from '../packages/interpreter/src/isa/manifest';

const issues = validateIsaManifest();
if (issues.length > 0) {
  throw new Error(
    `Cannot generate ISA report from an invalid manifest:\n${issues
      .map((issue) => `${issue.formId}: ${issue.message}`)
      .join('\n')}`
  );
}

const summary = summarizeIsaCoverage();
const outputPath = resolve('docs/generated/M68000_ISA_COVERAGE.md');
mkdirSync(resolve('docs/generated'), { recursive: true });

const rows = [...M68000_ISA_MANIFEST]
  .sort(
    (left, right) =>
      left.minimumProfile.localeCompare(right.minimumProfile) ||
      left.mnemonic.localeCompare(right.mnemonic) ||
      left.id.localeCompare(right.id)
  )
  .map((instruction) => {
    const pipelineEvidence =
      instruction.support === 'conformant'
        ? 'source encoder; binary decoder; strict executor'
        : instruction.support === 'extension-only'
          ? 'profile-gated decoder and executor'
          : 'Easy68K compatibility adapter';
    const testEvidence =
      instruction.support === 'conformant'
        ? 'deterministic CPU; all-opcode classifier; MAME corpus; Musashi/Moira sample'
        : instruction.support === 'extension-only'
          ? 'profile legality and execution tests'
          : 'Easy68K integration, worker, and IDE tests';
    return `| \`${instruction.id}\` | ${instruction.minimumProfile} | ${instruction.sizes.join(
      ', '
    )} | ${instruction.support} | ${pipelineEvidence} | ${testEvidence} |`;
  });

const report = `# Generated M68000 ISA Coverage

Generated by \`yarn generate:isa-report\`. Do not edit this file by hand.

## Summary

| Metric | Count |
| --- | ---: |
| Total instruction forms | ${summary.totalForms} |
| Unique mnemonics | ${summary.uniqueMnemonics} |
| Strict MC68000 forms | ${summary.byProfile.m68000} |
| MC68010 extension forms | ${summary.byProfile.m68010} |
| Easy68K compatibility forms | ${summary.byProfile.easy68k} |
| Legacy runtime only | ${summary.bySupport['legacy-only']} |
| Strict core, partial | ${summary.bySupport['strict-core-partial']} |
| Integrated, audit required | ${summary.bySupport['integrated-needs-audit']} |
| Conformant | ${summary.bySupport.conformant} |
| Missing | ${summary.bySupport.missing} |
| Extension only | ${summary.bySupport['extension-only']} |
| Compatibility only | ${summary.bySupport['compatibility-only']} |

## Evidence and audit policy

\`conformant\` means the form is encoded into real bytes, decoded and executed by
the authoritative strict core, covered by deterministic tests and the complete
65,536-word classifier, and represented in the pinned MAME family corpus. Run
\`yarn test:oracles\` for bounded Musashi/Moira differentials and
\`yarn test:oracles:mame\` for all 317,500 MAME vectors.

The full MAME audit fails on unexplained differences. Its generated JSON keeps
the reviewed temporal quarantines separate from exact matches: MC68000 internal
address-error frames/bus sequencing, prefetch-stage fault attribution, and
undefined CHK condition bits saved in an exception frame.

## Forms

| Form | Minimum profile | Sizes | Support | Pipeline evidence | Test evidence |
| --- | --- | --- | --- | --- | --- |
${rows.join('\n')}
`;

async function main(): Promise<void> {
  writeFileSync(outputPath, await format(report, { parser: 'markdown' }));
}

void main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
