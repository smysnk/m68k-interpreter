; EASy68K autovectors. Enable Auto IRQ 1 in the Hardware panel or press IRQ 1.
ORG $64
IRQ1_VECTOR DC.L IRQ1_HANDLER
ORG $68
IRQ2_VECTOR DC.L IRQ2_HANDLER
ORG $6C
IRQ3_VECTOR DC.L IRQ3_HANDLER
ORG $70
IRQ4_VECTOR DC.L IRQ4_HANDLER
ORG $74
IRQ5_VECTOR DC.L IRQ5_HANDLER
ORG $78
IRQ6_VECTOR DC.L IRQ6_HANDLER
ORG $7C
IRQ7_VECTOR DC.L IRQ7_HANDLER

ORG $1000
START
  BRA START

IRQ1_HANDLER
  ADDQ.B #1,IRQ_COUNT
  MOVE.B IRQ_COUNT,$E00010
  RTE
IRQ2_HANDLER
  ADDQ.B #2,IRQ_COUNT
  MOVE.B IRQ_COUNT,$E00010
  RTE
IRQ3_HANDLER
  ADDQ.B #3,IRQ_COUNT
  MOVE.B IRQ_COUNT,$E00010
  RTE
IRQ4_HANDLER
  ADDQ.B #4,IRQ_COUNT
  MOVE.B IRQ_COUNT,$E00010
  RTE
IRQ5_HANDLER
  ADDQ.B #5,IRQ_COUNT
  MOVE.B IRQ_COUNT,$E00010
  RTE
IRQ6_HANDLER
  ADDQ.B #6,IRQ_COUNT
  MOVE.B IRQ_COUNT,$E00010
  RTE
IRQ7_HANDLER
  ADDQ.B #7,IRQ_COUNT
  MOVE.B IRQ_COUNT,$E00010
  RTE

IRQ_COUNT DC.B 0
  END START
